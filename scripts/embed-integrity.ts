/**
 * Embed player integrity registry (security audit: SRI).
 *
 * Embed snippets carry `integrity="sha384-..."` for the player file, so the bytes
 * served at a given player filename must NEVER change. This script owns
 * src/embed/integrity.ts (version -> sha384) and enforces the rule.
 *
 *   npx tsx scripts/embed-integrity.ts            check (default; npm run verify:embed-integrity)
 *   npx tsx scripts/embed-integrity.ts --write    register the CURRENT version's hash (first release only)
 *   npx tsx scripts/embed-integrity.ts --write --force   deliberately overwrite (never after release)
 *   npx tsx scripts/embed-integrity.ts --write --force --version=0.1.0   same, for a frozen older version
 *
 * ONE-TIME EXCEPTION (decided 2026-11-19, before any third party had adopted an SRI hash): the
 * registered bytes of 0.1.0 and 0.2.0 were corrected once. 0.1.0 had silently changed several times
 * since July without a bump (so the name was ambiguous), and both versions needed the player-feedback
 * behaviour. After that date the rule is absolute: --force on a version that has been out since is a
 * bug, not a tool. See EMBED.md, "Subresource Integrity".
 *
 * Needs a built dist/ (`npm run build`). Check mode fails when:
 *   - the current EMBED_VERSION has no registry entry,
 *   - any registered version's file is missing from dist/embed/ or its bytes differ,
 *   - dist/embed/ serves a player file the registry does not know,
 *   - a MUTABLE ALIAS (sombra-player.latest.umd.js, sombra-player.<major>.umd.js) is missing,
 *     differs from the newest registered release of its line, or names a major with no release.
 *     Aliases are deliberately not registered (they change on each release, so they carry no SRI).
 */
import { createHash } from 'crypto'
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs'
import { EMBED_VERSION } from '../src/embed/version'
import { PLAYER_INTEGRITY } from '../src/embed/integrity'

const DIR = 'dist/embed'
const REGISTRY = 'src/embed/integrity.ts'
const sri = (buf: Buffer) => 'sha384-' + createHash('sha384').update(buf).digest('base64')
const fileFor = (v: string) => `sombra-player.${v}.umd.js`
const write = process.argv.includes('--write')
const force = process.argv.includes('--force')
const target = process.argv.find((a) => a.startsWith('--version='))?.split('=')[1] ?? EMBED_VERSION

function fail(msg: string): never { console.error(`  [FAIL] ${msg}`); process.exit(1) }

if (!existsSync(DIR)) fail(`${DIR} not found: run \`npm run build\` first`)

if (write) {
  const p = `${DIR}/${fileFor(target)}`
  if (!existsSync(p)) fail(`${p} not found: run \`npm run build\` first`)
  const h = sri(readFileSync(p))
  const have = PLAYER_INTEGRITY[target]
  if (have && have !== h && !force) fail(`${target} is already registered with a DIFFERENT hash. Released bytes must never change: bump EMBED_VERSION in src/embed/version.ts instead (--force was used once, on 2026-11-19, as a documented pre-adoption correction; it is not a routine tool).`)
  const next = { ...PLAYER_INTEGRITY, [target]: h }
  const body = Object.keys(next).sort().map((v) => `  '${v}': '${next[v]}',`).join('\n')
  writeFileSync(REGISTRY, `// GENERATED by scripts/embed-integrity.ts --write. Do not edit by hand.\n// sha384 of each RELEASED player file. These bytes must never change: see src/embed/version.ts.\nexport const PLAYER_INTEGRITY: Record<string, string> = {\n${body}\n}\n`)
  console.log(`registered ${target}: ${h}`)
  process.exit(0)
}

let bad = 0
const check = (name: string, ok: boolean, detail = '') => { if (ok) console.log(`  [PASS] ${name}`); else { bad++; console.log(`  [FAIL] ${name}${detail ? ' — ' + detail : ''}`) } }

check(`current version ${EMBED_VERSION} has a registry entry`, !!PLAYER_INTEGRITY[EMBED_VERSION], 'run: npm run embed:integrity -- --write')
for (const [v, want] of Object.entries(PLAYER_INTEGRITY)) {
  const p = `${DIR}/${fileFor(v)}`
  if (!existsSync(p)) { check(`${fileFor(v)} is served`, false, 'missing from dist/embed/ (old versions must stay in public/embed/)'); continue }
  const got = sri(readFileSync(p))
  check(`${fileFor(v)} bytes match the registered hash`, got === want, got === want ? '' : 'player bytes changed under a released version: bump EMBED_VERSION and run `npm run embed:integrity -- --write`')
}
const ALIAS_RE = /^sombra-player\.(latest|\d+)\.umd\.js$/
const served = readdirSync(DIR).filter((f) => /^sombra-player\..+\.umd\.js$/.test(f) && !ALIAS_RE.test(f))
const registered = new Set(Object.keys(PLAYER_INTEGRITY).map(fileFor))
for (const f of served) check(`${f} is registered`, registered.has(f), 'a served player file with no registry entry cannot be integrity-checked')

// Mutable aliases: each must equal the newest registered release of its line.
const cmp = (a: string, b: string) => { const x = a.split('.').map(Number), y = b.split('.').map(Number); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0 }
const versions = Object.keys(PLAYER_INTEGRITY).sort(cmp)
const newestOf = (pred: (v: string) => boolean) => versions.filter(pred).pop()
const aliasWant = new Map<string, string>([['sombra-player.latest.umd.js', newestOf(() => true)!]])
for (const major of new Set(versions.map((v) => v.split('.')[0]))) aliasWant.set(`sombra-player.${major}.umd.js`, newestOf((v) => v.split('.')[0] === major)!)
for (const [alias, v] of aliasWant) {
  const a = `${DIR}/${alias}`, r = `${DIR}/${fileFor(v)}`
  if (!existsSync(a)) { check(`alias ${alias} is served`, false, `missing from dist/embed/ (freeze it into public/embed/ when its major is superseded)`); continue }
  check(`alias ${alias} equals the newest release of its line (${v})`, existsSync(r) && readFileSync(a).equals(readFileSync(r)))
}
for (const f of readdirSync(DIR).filter((f) => ALIAS_RE.test(f))) check(`${f} names a line that has a release`, aliasWant.has(f), 'an alias for a version line with no registered release')
console.log(bad ? `\n${bad} FAILED` : '\nAll embed integrity checks passed')
process.exit(bad ? 1 : 0)
